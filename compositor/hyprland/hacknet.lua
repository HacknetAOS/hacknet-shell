}

-- ---------------------------------------------------------------- keybinds
local mainMod = "SUPER"

-- App Opener / Search Bar: Super key alone or Super+Space opens search bar
hl.bind(mainMod .. " + SPACE", hl.dsp.exec_cmd("hacknet-launcher"))
hl.bind(mainMod,               hl.dsp.exec_cmd("hacknet-launcher"))

-- Terminal: Super+Enter opens a NEW left dock terminal slot (own NetMap node)
hl.bind(mainMod .. " + RETURN",       hl.dsp.exec_cmd("hacknet-dock-term"))

-- Super+Shift+Enter opens a stage terminal (for running commands in DISPLAY)
hl.bind(mainMod .. " + SHIFT + RETURN", hl.dsp.exec_cmd("hacknet-term --app-id hacknet-stage -e bash -lc 'fastfetch; exec bash'"))

-- Super+Tab cycles the next stage window (forward)
hl.bind(mainMod .. " + TAB",          hl.dsp.exec_cmd("hacknetctl cycle 1"))

-- Super+Shift+Tab cycles the previous stage window (backward)
hl.bind(mainMod .. " + SHIFT + TAB",  hl.dsp.exec_cmd("hacknetctl cycle -1"))

-- Super+F1 shows help
hl.bind(mainMod .. " + F1",           hl.dsp.exec_cmd("hacknetctl notify 'Help' 'Super+Enter: terminal | Super+Shift+Enter: stage | Super+Q: close | Super+Tab: cycle | Super+E: files | Print: screenshot'"))

-- Window closing: Super+Q, Super+W, Alt+F4
hl.bind(mainMod .. " + Q",            hl.dsp.window.close())
hl.bind(mainMod .. " + W",            hl.dsp.window.close())
hl.bind("ALT + F4",                   hl.dsp.window.close())

-- REMOVED: Super+Shift+Q to logout (was too easy to hit accidentally)
-- Use the session menu instead (gear icon -> power button)
-- REMOVED: Super+V (RAM gutter) and Super+Grave (theme) — the Control Center
-- handles the gutter toggle and theme switching now.

-- Desktops: Super+Shift+N adds one, Super+Left/Right cycles them, Super+1..5 switches.
hl.bind(mainMod .. " + SHIFT + N",    hl.dsp.exec_cmd("hacknetctl desktop-add"))
hl.bind(mainMod .. " + RIGHT",        hl.dsp.exec_cmd("hacknetctl desktop-switch-next"))
hl.bind(mainMod .. " + LEFT",         hl.dsp.exec_cmd("hacknetctl desktop-switch-prev"))
hl.bind(mainMod .. " + 1",            hl.dsp.exec_cmd("hacknetctl desktop-switch 1"))
hl.bind(mainMod .. " + 2",            hl.dsp.exec_cmd("hacknetctl desktop-switch 2"))
hl.bind(mainMod .. " + 3",            hl.dsp.exec_cmd("hacknetctl desktop-switch 3"))
hl.bind(mainMod .. " + 4",            hl.dsp.exec_cmd("hacknetctl desktop-switch 4"))
hl.bind(mainMod .. " + 5",            hl.dsp.exec_cmd("hacknetctl desktop-switch 5"))

-- Fullscreen the focused stage window (creates its own desktop-sized view).
hl.bind(mainMod .. " + F",            hl.dsp.exec_cmd("hacknetctl fullscreen-toggle"))

-- Super+L locks session
hl.bind(mainMod .. " + L",            hl.dsp.exec_cmd("sh -c 'mkdir -p ~/.local/state/hacknet && touch ~/.local/state/hacknet/locked'"))

-- Super+E opens file manager (thunar)
hl.bind(mainMod .. " + E",            hl.dsp.exec_cmd("thunar"))

-- Volume controls
hl.bind("XF86AudioRaiseVolume", hl.dsp.exec_cmd("hacknetctl volume up"))
hl.bind("XF86AudioLowerVolume", hl.dsp.exec_cmd("hacknetctl volume down"))
hl.bind("XF86AudioMute",        hl.dsp.exec_cmd("hacknetctl volume mute"))
hl.bind("XF86AudioPlay",        hl.dsp.exec_cmd("hacknetctl media play_pause"))
hl.bind("XF86AudioNext",        hl.dsp.exec_cmd("hacknetctl media next"))
hl.bind("XF86AudioPrev",        hl.dsp.exec_cmd("hacknetctl media previous"))

-- Screenshots (saves to Pictures, copies to clipboard, and notifies)
hl.bind("PRINT", hl.dsp.exec_cmd("sh -c 'mkdir -p \"$HOME/Pictures\"; f=\"$HOME/Pictures/Screenshot_$(date +%Y%m%d_%H%M%S).png\"; grim \"$f\" && (wl-copy < \"$f\" 2>/dev/null || true) && hacknetctl notify \"Screenshot\" \"Saved to ~/Pictures\"'"))
hl.bind(mainMod .. " + SHIFT + PRINT", hl.dsp.exec_cmd("sh -c 'mkdir -p \"$HOME/Pictures\"; f=\"$HOME/Pictures/Screenshot_$(date +%Y%m%d_%H%M%S).png\"; grim -g \"$(slurp)\" \"$f\" && (wl-copy < \"$f\" 2>/dev/null || true) && hacknetctl notify \"Screenshot\" \"Region saved to ~/Pictures\"'"))
hl.bind(mainMod .. " + PRINT", hl.dsp.exec_cmd("sh -c 'mkdir -p \"$HOME/Pictures\"; f=\"$HOME/Pictures/Screenshot_$(date +%Y%m%d_%H%M%S).png\"; grim \"$f\" && (wl-copy < \"$f\" 2>/dev/null || true) && hacknetctl notify \"Screenshot\" \"Saved to ~/Pictures\"'"))

-- ---------------------------------------------------------------- exec-on-startup
hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP=HacknetOS XDG_SESSION_DESKTOP=HacknetOS XDG_SESSION_TYPE=wayland")
hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP XDG_SESSION_DESKTOP XDG_SESSION_TYPE")
hl.exec_cmd("sh -c 'systemctl --user reset-failed xdg-desktop-portal-hyprland xdg-desktop-portal-gtk 2>/dev/null; systemctl --user restart xdg-desktop-portal-gtk xdg-desktop-portal 2>/dev/null'")
hl.exec_cmd("hacknetd")
hl.exec_cmd("sh -c 'sleep 2; exec quickshell -p /usr/share/quickshell/hacknet/shell.qml'")
-- The TERMINAL region is a real foot window placed by the daemon. Start it here
-- and respawn it if no docked terminal is open, so the pane is never empty.
hl.exec_cmd("sh -c 'while :; do pgrep -f \"[f]oot.*hacknet-term\" >/dev/null 2>&1 || hacknet-term --app-id hacknet-term; sleep 2; done'")

